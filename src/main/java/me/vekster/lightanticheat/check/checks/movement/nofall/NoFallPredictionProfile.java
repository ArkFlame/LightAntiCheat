    public static float byDistance(int jumpAmplifier, double fallDistance) {
        int profile = profileForAmplifier(jumpAmplifier);
        double[] thresholds = DISTANCE_THRESHOLDS[profile];
        float[] limits = DISTANCE_LIMITS[profile];
        float best = -1F;
        for (int i = 0; i < thresholds.length; i++) {
            if (Math.abs(thresholds[i]) >= Math.abs(fallDistance)) {
                float v = limits[i];
                best = (best == -1F) ? v : Math.min(best, v);
            }
        }
        return best;
    }

    /**
     * Computes the per-event VELOCITY after {@code events} iterations of
     * {@code (v - 0.08) * 0.98} starting from initial jump velocity
     * {@code 0.42 + 0.1 * amplifier}. Returns -1F if {@code events} is
     * non-positive. This is retained for diagnostic parity with
     * {@code VanillaVerticalPhysics}; it is intentionally NOT used to
     * populate {@link #EVENT_LIMITS} because bit-exact comparison against
     * the extracted fixture fails (the fixture stores cumulative fall
     * distance, not per-event velocity).
     */
    public static float diagnosticRecurrenceByEvents(int jumpAmplifier, int events) {
        if (events <= 0) return -1F;
        int profile = profileForAmplifier(jumpAmplifier);
        double velocity = 0.42D + profile * 0.1D;
        for (int t = 0; t < events; t++) {
            velocity = (velocity - 0.08D) * 0.98D;
        }
        return (float) velocity;
    }
